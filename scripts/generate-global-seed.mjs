#!/usr/bin/env node
/**
 * Generates scripts/seed-global-chats.sql from src/shared/demo-global-chats.ts.
 * Run via: npm run db:seed:generate
 */
import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const outPath = join(__dirname, "seed-global-chats.sql");

const evalScript = `
import { getDemoGlobalChats } from ${JSON.stringify(join(root, "src/shared/demo-global-chats.ts"))};
import { estimateReplyUsage } from ${JSON.stringify(join(root, "src/shared/usage.ts"))};

const chats = getDemoGlobalChats();
const enriched = chats.map((chat) => {
  let lastUser = "";
  const messages = chat.messages.map((m) => {
    if (m.role === "user") {
      lastUser = m.content;
      return { ...m, input_tokens: null, output_tokens: null, cost_usd: null, latency_ms: null, confidence: null };
    }
    const usage = estimateReplyUsage(lastUser, m.content);
    return {
      ...m,
      input_tokens: usage.inputTokens,
      output_tokens: usage.outputTokens,
      cost_usd: usage.costUsd,
      latency_ms: usage.latencyMs,
      confidence: m.suggested_memory ? 0.72 : 0.93,
    };
  });
  return { ...chat, messages };
});
process.stdout.write(JSON.stringify(enriched));
`;

const result = spawnSync("npx", ["tsx", "-e", evalScript], {
	cwd: root,
	encoding: "utf8",
	maxBuffer: 32 * 1024 * 1024,
	env: { ...process.env },
});

if (result.status !== 0) {
	console.error(result.stderr || result.stdout || "tsx failed");
	process.exit(result.status ?? 1);
}

const chats = JSON.parse(result.stdout);

function sqlString(value) {
	if (value === null || value === undefined) return "NULL";
	return `'${String(value).replace(/'/g, "''")}'`;
}

function sqlJson(value) {
	if (value === null || value === undefined) return "NULL";
	return sqlString(JSON.stringify(value));
}

function sqlNumber(value) {
	if (value === null || value === undefined) return "NULL";
	return String(value);
}

/** Conversation base agoHours, plus optional seconds forward (later messages). */
function tsExpr(hours, extraSeconds = 0) {
	if (extraSeconds === 0) {
		return `strftime('%Y-%m-%dT%H:%M:%fZ', 'now', '-${hours} hours')`;
	}
	return `strftime('%Y-%m-%dT%H:%M:%fZ', 'now', '-${hours} hours', '+${extraSeconds} seconds')`;
}

const lines = [];
lines.push("-- AUTO-GENERATED by scripts/generate-global-seed.mjs");
lines.push("-- Source: src/shared/demo-global-chats.ts");
lines.push("-- Do not edit by hand; re-run: npm run db:seed:generate");
lines.push("");
lines.push("DELETE FROM chat_messages WHERE conversation_id IN (SELECT id FROM conversations WHERE scope = 'global');");
lines.push("DELETE FROM chat_messages WHERE conversation_id BETWEEN 9001 AND 9012;");
lines.push("DELETE FROM conversations WHERE id BETWEEN 9001 AND 9012;");
lines.push("DELETE FROM conversations WHERE scope = 'global';");
lines.push("");

lines.push(
	"INSERT INTO conversations (id, title, scope, author_name, author_slack_username, source_kind, source_channel, created_at, updated_at, last_read_at) VALUES",
);

const MESSAGE_GAP_SECONDS = 90;

const convRows = chats.map((chat, idx) => {
	const msgCount = chat.messages.length;
	const lastOffsetSec = (msgCount - 1) * MESSAGE_GAP_SECONDS;
	const created = tsExpr(chat.agoHours, 0);
	const updated = tsExpr(chat.agoHours, lastOffsetSec);
	// Unread when last_read_at IS NULL or before assistant messages.
	const lastRead = chat.startUnread ? "NULL" : updated;
	const row = [
		chat.id,
		sqlString(chat.title),
		sqlString("global"),
		sqlString(chat.authorName),
		sqlString(chat.authorSlackUsername),
		sqlString(chat.sourceKind),
		sqlString(chat.sourceChannel),
		created,
		updated,
		lastRead,
	].join(", ");
	return `\t(${row})${idx === chats.length - 1 ? ";" : ","}`;
});
lines.push(...convRows);
lines.push("");

lines.push(
	"INSERT INTO chat_messages (conversation_id, role, content, suggested_memory, artifact, working, confidence, input_tokens, output_tokens, cost_usd, latency_ms, created_at) VALUES",
);

const msgRows = [];
for (const chat of chats) {
	chat.messages.forEach((m, i) => {
		msgRows.push({
			chat,
			m,
			created: tsExpr(chat.agoHours, i * MESSAGE_GAP_SECONDS),
		});
	});
}

msgRows.forEach(({ chat, m, created }, idx) => {
	const row = [
		chat.id,
		sqlString(m.role),
		sqlString(m.content),
		sqlString(m.suggested_memory ?? null),
		sqlJson(m.artifact ?? null),
		sqlJson(m.working ?? null),
		sqlNumber(m.confidence),
		sqlNumber(m.input_tokens),
		sqlNumber(m.output_tokens),
		sqlNumber(m.cost_usd),
		sqlNumber(m.latency_ms),
		created,
	].join(", ");
	lines.push(`\t(${row})${idx === msgRows.length - 1 ? ";" : ","}`);
});

lines.push("");

writeFileSync(outPath, lines.join("\n"), "utf8");
console.log(`Wrote ${outPath} (${chats.length} conversations, ${msgRows.length} messages)`);
